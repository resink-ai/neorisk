class _Gen:
    def __init__(self, part: str, machines: list, plan, default_depth: int):
        self.part, self.ms, self.plan = part, machines, plan
        self.default_depth = default_depth          # budget.max_spawn_depth (D72, F-21)
        self.by_name = {m.name: m for m in machines}
        self.funcs: list[str] = []
        self.need = Need()
        self.params: dict[str, dict[str, Any]] = {m.name: {} for m in machines}
        self.copies: dict[tuple[str, str], str] = {}
        self.copy_src: list[str] = []
        self.files: set[str] = set()
        self.stat = L.stat_layout(machines)
        self.next_site: dict[tuple[str, int], int] = {}
        self.trans: dict[str, list[tuple]] = {m.name: [] for m in machines}
        self.responses: dict[tuple[str, str], int] = {}
        self.now: dict[str, set[int]] = {m.name: set() for m in machines}   # OP_NOW codes

    # ---------------------------------------------------------------- small pieces
    def fn(self, name: str, params: str, body: list[str]) -> None:
        self.funcs.append(f"def {name}({params}):\n" + "\n".join(f"    {ln}" for ln in body))

    def site(self, m, st) -> int:
        """The next draw site of state `st`'s block, or of the machine's root block when `st`
        is None (START-time draws: member attrs, root_init; D65, F-09)."""
        k = (m.name, 0 if st is None else st.code)
        j = self.next_site.get(k, 0)
        self.next_site[k] = j + 1
        if st is None:
            return L.root_site(m, j)
        return L.state_site(m, st.code - 1, j)

    def param(self, m, name: str, value) -> str:
        """Register an op parameter and return its full config path (D77, F-10). A full path
        needs no alias, so every generated function can use it (F-19); this plan's sketches
        write `c.<name>` for `ctx.cfg.x_<m>.<name>`."""
        self.params[m.name][name] = value
        return f"ctx.cfg.x_{m.name}.{name}"

    def lit(self, m, value) -> str:
        """A literal int/float/bool as a parameter (D77: `--set` never changes the source)."""
        v = int(value) if isinstance(value, bool) else value
        return self.param(m, f"v{len(self.params[m.name])}", v)

    def reserve(self, need: Need) -> list[str]:
        self.need = self.need.union(need)
        src = need.src()
        return [f"if not out.reserve({src}):", "    return RETRY"] if src else []

    def actor(self, m) -> str:
        return "ctx.self_id" if m.member_table is None else f"loc.{m.name}__actor[i]"

    def enter_call(self, m, target: str, inst: str = "i") -> str:
        code = m.code(target)
        if target in m.finals:
            return f"mx_end_{m.name}(ctx, s, loc, cmd, out, {inst}, {code})"
        return f"mx_enter_{m.name}_{code}(ctx, s, loc, cmd, out, {inst})"

    def tid(self, m, st, kind: str, key, target: str, chain) -> int:
        lst = self.trans[m.name]
        lst.append((st, kind, key, target, chain))
        if len(lst) > MAX_TRANSITIONS:
            raise PackError(f"machine {m.name}: more than {MAX_TRANSITIONS} transitions")
        return len(lst) - 1

    def delay(self, m, st, name: str, d: Dist | None) -> str:
        if d is None:
            return "ctx.t"
        return f"ctx.t + ctx.rng.dist_us(site={self.site(m, st)}, d={self.param(m, name, d)})"

    # ---------------------------------------------------------------- values (std vocabulary)
    def value(self, m, st, v, ltype=None) -> tuple[str, Need]:
        if isinstance(v, h.Actor):
            return self.actor(m), Need()
        if isinstance(v, h.ParentActor):
            return f"loc.{m.name}__pactor[i]", Need()
        if isinstance(v, h.Col):
            return f"s.{v.name}", Need()
        if isinstance(v, h.Field):
            return f"loc.{m.name}__{v.name}[i]", Need()
        if isinstance(v, h.NewId):
            return f"out.new_id({v.ns!r})", Need(creates=Counter({v.ns: 1}))
        if isinstance(v, h.Now):
            return "ctx.t", Need()
        if isinstance(v, h.After):
            return self.delay(m, st, f"v{len(self.params[m.name])}", v.delay), Need()
        if isinstance(v, h.Near):
            base, hi = self.lit(m, v.value), self.lit(m, int(v.value * v.above))
            return (f"{base} + ctx.rng.uniform_int(site={self.site(m, st)}, lo=0, hi={hi})",
                    Need())
        if isinstance(v, Dist) and v.kind == CATEGORICAL:
            labels = list(v.labels)
            if ltype is not None and ltype.kind == "cat":
                codes = tuple(ltype.values.index(x) for x in labels)
            else:
                codes = tuple(int(x) for x in labels)
            p = self.param(m, f"v{len(self.params[m.name])}", tuple(float(w) for w in v.weights))
            return (f"{codes!r}[ctx.rng.categorical(site={self.site(m, st)}, p={p})]", Need())
        if isinstance(v, Dist) and v.kind == UNIFORM_INT:
            lo, hi = self.lit(m, int(v.params[0])), self.lit(m, int(v.params[1]))
            return f"ctx.rng.uniform_int(site={self.site(m, st)}, lo={lo}, hi={hi})", Need()
        if isinstance(v, str):
            if ltype is None or ltype.kind != "cat" or v not in ltype.values:
                raise PackError(f"machine {m.name}: {v!r} is not a category of this column")
            return self.lit(m, ltype.values.index(v)), Need()      # the category's code
        if isinstance(v, (bool, int, float)):
            return self.lit(m, v), Need()
        raise PackError(f"machine {m.name}: unsupported value {v!r}")

    # ---------------------------------------------------------------- parts
    def make_part(self, m, st, act, fname: str) -> tuple[str, Need]:
        """Define the function of one part; return the call expression and its need."""
        if isinstance(act, ActionSpec):
            key = (m.name, act.name)
            if key not in self.copies:
                name, src = copy_action(act, m, len(self.copies))
                self.copies[key] = name
                self.copy_src.append(src)
                self.files.add(act.module_file)
            return f"{self.copies[key]}(ctx, s, loc, cmd, out, i)", Need.of(act.max)
        if isinstance(act, h.Emit):
            ev = self.plan.event(act.event)
            cols = {c.name: c.ltype for c in ev.cols}
            args, need = [], Need(records=Counter({act.event: 1}))
            for name, v in act.values:
                src, n = self.value(m, st, v, cols.get(name))
                args.append(f"{name}={src}")
                need = need.add(n)
            self.fn(fname, "ctx, s, loc, cmd, out, i",
                    [f"out.emit_{act.event}(ctx.t, {', '.join(args)})", "return COMMIT"])
            return f"{fname}(ctx, s, loc, cmd, out, i)", need
        return self.part_more(m, st, act, fname)            # Tasks 7, 8

    def part_more(self, m, st, act, fname):
        call = f"{fname}(ctx, s, loc, cmd, out, i)"
        if isinstance(act, h.Spawn):
            body, need = self.spawn_body(m, st, act.machine, act.n, act.stagger, act.fields)
            self.fn(fname, "ctx, s, loc, cmd, out, i", body + ["return COMMIT"])
            return call, need
        if isinstance(act, h.SendParent):
            self.fn(fname, "ctx, s, loc, cmd, out, i", self.send_parent(m, act.msg))
            return call, Need(timers=1)
        if isinstance(act, h.SetField):
            src, need = self.value(m, st, act.value)
            self.fn(fname, "ctx, s, loc, cmd, out, i", [
                f"loc.{m.name}__{act.name}[i] {'+=' if act.add else '='} {src}", "return COMMIT"])
            return call, need
        raise PackError(f"machine {m.name}: {type(act).__name__} arrives in a later task")

    # ---------------------------------------------------------------- family (D69, D70)
    def leave_join(self, m) -> list[str]:
        """Leaving a join state (completion, timeout or ending) marks later messages late."""
        out = []
        for j in m.states:
            if j.join is not None:
                out += [f"if loc.{m.name}__st[i] == {j.code}:",
                        f"    loc.{m.name}__jl[i] = {2 if j.late == 'count' else 1}"]
        return out

    def now_timer(self, m, inst: str, gen: str, target: str, when: str = "ctx.t",
                  prio: str = "PRIO_CONTINUE") -> str:
        """A firing that enters `target` (`OP_NOW`; `mx_fire` dispatches its code): immediate
        by default (D68), or at `when` with `prio` (a staggered spawn)."""
        code = m.code(target)
        self.now[m.name].add(code)
        return (f"out.timer({when}, MX_FIRE, prio={prio}, tag=mx_tag({m.index}, {inst}, "
                f"{gen}, {L.OP_NOW}, {code}))")

    def operand(self, m, st, v) -> str:
        if isinstance(v, h.Repeats):
            return f"loc.{m.name}__rep[i]"
        if isinstance(v, (h.Field, h.Col)):
            return self.value(m, st, v)[0]
        if isinstance(v, int) and not isinstance(v, bool):
            return self.lit(m, v)
        raise PackError(f"machine {m.name}: state {st.name!r}: condition operands are ints, "
                        f"std.field, std.col or the repeat count, got {v!r}")

    def cond(self, m, st, c: h.Cond) -> str:
        op = {"ge": ">=", "le": "<=", "eq": "=="}[c.op]
        return f"({self.operand(m, st, c.a)} {op} {self.operand(m, st, c.b)})"

    def count(self, m, st, v, name: str | None = None) -> str:
        """A count source (F-18): int parameter, std.col/std.field, or a Dist drawn here."""
        if isinstance(v, int) and not isinstance(v, bool):
            return self.param(m, name, int(v)) if name else self.lit(m, int(v))
        if isinstance(v, (h.Field, h.Col)):
            return self.value(m, st, v)[0]
        if isinstance(v, Dist) and v.kind == GEOMETRIC:
            draw = (f"ctx.rng.geometric(site={self.site(m, st)}, "
                    f"mean={self.lit(m, float(v.params[0]))})")
            if v.params[1] > 0:                              # max=0 is unbounded
                return f"min({draw}, {self.lit(m, int(v.params[1]))})"
            return draw
        if isinstance(v, Dist) and v.kind in (UNIFORM_INT, CATEGORICAL):
            return self.value(m, st, v)[0]
        raise PackError(f"machine {m.name}: state {st.name!r}: unsupported count {v!r}")

    def member_actor(self, cm) -> tuple[list[str], Need]:
        """The `actor` of a spawned instance of `cm` (Task 10: a member row for cohort
        machines)."""
        return ["actor = ctx.self_id"], Need()

    def init_field(self, m, st, cm, f: str, v) -> tuple[list[str], Need]:
        """A spawn field initializer, evaluated in the parent's context."""
        dst = f"loc.{cm.name}__{f}[j]"
        if isinstance(v, h.PickRef):
            lines = [(f"{dst} = ctx.refs.{v.refs}.pick(ctx.self_id, "
                     f"ctx.rng.uniform(site={self.site(m, st)}))")]
            if v.parent_share is not None:
                share = self.lit(m, float(v.parent_share))
                lines += [f"if ctx.rng.bernoulli(site={self.site(m, st)}, p={share}):",
                          f"    {dst} = loc.{m.name}__{f}[i]"]
            return lines, Need()
        src, need = self.value(m, st, v)
        return [f"{dst} = {src}"], need

    def spawn_body(self, m, st, child: str, n, stagger, fields) -> tuple[list[str], Need]:
        """Create `n` instances of `child` under instance `i` of `m` (same owner, D69, D72)."""
        cm, p = self.by_name[child], m.name
        q = cm.name
        if "maxdep" not in self.params[p]:
            depth = m.max_spawn_depth or self.default_depth
            if depth > L.MAX_DEPTH:
                raise PackError(f"machine {p}: max_spawn_depth {depth} exceeds {L.MAX_DEPTH} "
                                "(the instance depth field is i8)")
            self.param(m, "maxdep", int(depth))
        body = [f"n = {self.count(m, st, n)}",
                f"dep = loc.{p}__dep[i] + 1",
                f"if n > 0 and dep > ctx.cfg.x_{p}.maxdep:",
                f'    raise EngineError("{p}: spawn depth exceeds max_spawn_depth")',
                "for k_ in range(n):",
                f"    if loc.{p}__kids[i] >= {L.MAX_CHILDREN}:",
                f'        raise EngineError("{p}: more than {L.MAX_CHILDREN} children")',
                f"    j = mx_alloc_{q}(loc)",
                "    if j < 0:",
                f'        raise EngineError("{p}: no free {q} instance (max_instances)")']
        lines, per = self.member_actor(cm)
        body += ["    " + x for x in lines]
        body += [(f"    mx_init_{q}(loc, j, dep, i, {m.index}, loc.{p}__ep[i], loc.{p}__kids[i], "
                 f"actor, {self.actor(m)})"),
                 f"    loc.{p}__kids[i] += 1"]
        for f, v in fields:
            lines, need = self.init_field(m, st, cm, f, v)
            body += ["    " + x for x in lines]
            per = per.add(need)
        body.append(f"    out.mstat({self.stat[p] + 2}, 1)")
        if stagger is None:
            body.append(f"    {self.enter_call(cm, cm.initial, 'j')}")
            per = per.add(self.entry_need(cm, cm.initial))
        else:
            gap = (f"ctx.rng.dist_us(site={self.site(m, st)}, "
                   f"d={self.param(m, f'v{len(self.params[p])}', stagger)})")
            body += [f"    loc.{q}__st[j] = -1",              # reserved: mx_alloc skips it
                     "    " + self.now_timer(cm, "j", f"loc.{q}__gen[j]", cm.initial,
                                             when=f"ctx.t + k_ * {gap}", prio="PRIO_TIMER")]
            per = per.add(Need(timers=1))
        return body, per.times(cm.max_instances)

    def send_parent(self, m, msg: str) -> list[str]:
        """Count this child's message in its parent's join (`jb`/`jn`), whatever state the
        parent is in; a message after the parent left its join is late (D69)."""
        p = m.name
        body = [f"par = int(loc.{p}__par[i])", "if par < 0:", "    return COMMIT"]
        for pm in self.ms:
            joins = [j for j in pm.states if j.join is not None and j.join[1] == msg]
            if not joins or not _spawns(pm, p):
                continue
            q = pm.name
            injoin = " or ".join(f"loc.{q}__st[par] == {j.code}" for j in joins)
            body += [f"if loc.{p}__pm[i] == {pm.index}:",
                     f"    if loc.{q}__ep[par] != loc.{p}__pep[i]:",
                     "        return COMMIT",                       # the parent slot was reused
                     f"    injoin = {injoin}",
                     f"    if loc.{q}__jl[par] != 0 and not injoin:",
                     f"        if loc.{q}__jl[par] == 2:",
                     f"            out.mstat({self.stat[q]}, 1)",
                     "        return COMMIT",
                     f"    bit = 1 << int(loc.{p}__ord[i])",
                     f"    if (loc.{q}__jb[par] & bit) == 0:",
                     f"        loc.{q}__jb[par] |= bit",
                     f"        loc.{q}__jn[par] += 1",
                     f"        if injoin and loc.{q}__jn[par] >= loc.{q}__kids[par]:"]
            for j in joins:
                body += [f"            if loc.{q}__st[par] == {j.code}:",
                         "                " + self.now_timer(pm, "par", f"loc.{q}__gen[par]",
                                                             j.join[0])]
            body.append("    return COMMIT")
        body.append("return COMMIT")
        return body

    def repetition(self, m, t: int) -> None:
        """`mx_rep_<m>_<t>`: one repetition of a repeat state (D70)."""
        st, _kind, _key, _target, chain = self.trans[m.name][t]
        p, k = m.name, st.code
        d, prob, _ = st.repeat
        need = Need(timers=1)
        if st.then is not None:
            need = need.add(self.entry_need(m, st.then))
        call = fb = None
        if chain is not None:
            (prt,) = chain.parts
            call, an = self.make_part(m, st, prt.act, f"mx_part_{p}_{t}_0")
            if prt.fallback is not None:
                fb, fn = self.make_part(m, st, prt.fallback, f"mx_part_{p}_{t}_0f")
                an = an.union(fn)
            need = need.add(an)
        body = self.reserve(need)
        if call is not None:
            body.append(f"run = ctx.rng.bernoulli(site={self.site(m, st)}, "
                        f"p={self.param(m, f's{k}_rp', prob)})")
        body += [(f"nxt = ctx.rng.dist_us(site={self.site(m, st)}, "
                 f"d={self.param(m, f's{k}_rd', d)})")]
        if st.then is None:              # no stop: repeat until another op leaves, rep saturates
            body += [f"if loc.{p}__rep[i] < {L.REPEAT_CAP}:", f"    loc.{p}__rep[i] += 1"]
        else:
            body.append(f"loc.{p}__rep[i] += 1")
        rej = f"out.mstat({self.stat[p] + 1}, 1)"
        if call is not None:
            body += ["if run:", f"    rc = {call}", "    if rc != COMMIT:", f"        {rej}"]
            if fb is not None:
                body += [f"        rc = {fb}", "        if rc != COMMIT:", f"            {rej}"]
        if st.then is not None:          # validate: until / max_repeats need then=
            stop = f"loc.{p}__rep[i] >= loc.{p}__mr[i]"
            if st.until is not None:
                stop += f" or {self.cond(m, st, st.until)}"
            body += [f"if {stop}:", f"    {self.enter_call(m, st.then)}", "    return COMMIT"]
        body += [(f"out.timer(ctx.t + nxt, MX_FIRE, prio=PRIO_TIMER, tag=mx_tag({m.index}, i, "
                 f"loc.{p}__gen[i], {L.OP_REPEAT}, {t}))"),
                 "return COMMIT"]
        self.fn(f"mx_rep_{p}_{t}", "ctx, s, loc, cmd, out, i", body)

    def spawn_op(self, m, t: int) -> None:
        """`mx_sp_<m>_<t>`: a state's delayed spawn op."""
        st, _kind, j, _target, _chain = self.trans[m.name][t]
        child, _p, _d, n = st.spawn[j]
        body, need = self.spawn_body(m, st, child, n, None, ())
        self.fn(f"mx_sp_{m.name}_{t}", "ctx, s, loc, cmd, out, i",
                self.reserve(need) + body + ["return COMMIT"])

    # ---------------------------------------------------------------- entry, end, transitions
    def entry_need(self, m, target: str) -> Need:
        if target in m.finals:
            return Need()
        st = m.state(target)
        n = Need(timers=(1 if st.branch else 0) + len(st.timers))
        return n.add(self.entry_need_more(m, st))          # Tasks 7, 8

    def entry_need_more(self, m, st) -> Need:
        return Need(timers=len(st.spawn) + (1 if st.join is not None else 0)
                    + (2 if st.repeat is not None else 0))

    def enter(self, m, st) -> None:
        p, k = m.name, st.code
        body = self.leave_join(m) + [
                f"loc.{p}__st[i] = {k}", f"loc.{p}__gen[i] += 1", f"loc.{p}__rep[i] = 0",
                f"loc.{p}__t0[i] = ctx.t", f"out.mstat({self.stat[p] + 4 + k - 1}, 1)",
                f"g = loc.{p}__gen[i]"]
        for j, (target, d) in enumerate(st.timers):
            t = self.tid(m, st, "timer", j, target, None)
            body.append(f"out.timer({self.delay(m, st, f's{k}_t{j}_d', d)}, MX_FIRE, "
                        f"prio=PRIO_TIMER, tag=mx_tag({m.index}, i, g, {L.OP_TIMER}, {t}))")
        body += self.enter_more(m, st)                      # Tasks 7, 8
        if st.branch:
            body += self.branch_entry(m, st)
        self.fn(f"mx_enter_{p}_{k}", "ctx, s, loc, cmd, out, i", body)

    def enter_more(self, m, st) -> list[str]:
        p, k = m.name, st.code
        lines = []
        if st.join is not None:
            lines += [f"loc.{p}__jl[i] = 0",
                      f"if loc.{p}__jn[i] >= loc.{p}__kids[i]:",      # zero children included
                      "    " + self.now_timer(m, "i", "g", st.join[0])]
        if st.repeat is not None:
            mr = st.max_repeats
            if mr is None:
                src = str(L.REPEAT_CAP)
            elif isinstance(mr, int):
                src = self.count(m, st, mr, f"s{k}_mr")
            else:
                src = f"max(0, min({self.count(m, st, mr)}, {L.REPEAT_CAP}))"   # fits i16
            t = self.tid(m, st, "repeat", 0, st.then or st.name, st.repeat[2])
            lines += [f"loc.{p}__mr[i] = {src}",
                      (f"out.timer({self.delay(m, st, f's{k}_rd', st.repeat[0])}, MX_FIRE, "
                      f"prio=PRIO_TIMER, tag=mx_tag({m.index}, i, g, {L.OP_REPEAT}, {t}))")]
            if st.then is not None and (st.until is not None or mr is not None):
                stop = f"loc.{p}__mr[i] <= 0"                    # a maximum of 0 ends on entry
                if st.until is not None:
                    stop = f"{self.cond(m, st, st.until)} or {stop}"
                lines += [f"if {stop}:", "    " + self.now_timer(m, "i", "g", st.then)]
        for j, (_child, prob, d, _n) in enumerate(st.spawn):
            t = self.tid(m, st, "spawn", j, st.name, None)
            lines += [(f"if ctx.rng.bernoulli(site={self.site(m, st)}, "
                      f"p={self.param(m, f's{k}_sp{j}', prob)}):"),
                      (f"    out.timer({self.delay(m, st, f's{k}_sp{j}_d', d)}, MX_FIRE, "
                      f"prio=PRIO_TIMER, tag=mx_tag({m.index}, i, g, {L.OP_SPAWN}, {t}))")]
        return lines

    def branch_entry(self, m, st) -> list[str]:
        """Pick one outcome by one uniform draw (D71). The `None` outcome takes the unpicked
        mass; without one, the last outcome takes the rounding remainder (and, for `p_by`, the
        unpicked mass) unconditionally, so each outcome's timer appears once in the source
        (one draw site per delay)."""
        k = st.code
        lines = [f"u = ctx.rng.uniform(site={self.site(m, st)})", "acc = 0.0"]
        has_rest = any(o.p is None for o in st.branch)
        rest = None
        for j, o in enumerate(st.branch):
            t = self.tid(m, st, "branch", j, o.target, o.chain)
            push = (f"out.timer({self.delay(m, st, f's{k}_b{j}_d', o.delay)}, MX_FIRE, "
                    f"prio=PRIO_TIMER, tag=mx_tag({m.index}, i, g, {L.OP_BRANCH}, {t}))")
            if o.p is None:
                rest = push
                continue
            if not has_rest and j == len(st.branch) - 1:
                rest = push                                  # the rounding remainder
                break
            if isinstance(o.p, h.PBy):
                lines.append(f"pb = {self.param(m, f's{k}_b{j}_po', o.p.otherwise)}")
                for q, (value, prob) in enumerate(o.p.probs):
                    lines += [f"if s.{o.p.col} == {value!r}:",
                              f"    pb = {self.param(m, f's{k}_b{j}_p{q}', prob)}"]
                lines.append("acc += pb")
            else:
                lines.append(f"acc += {self.param(m, f's{k}_b{j}_p', float(o.p))}")
            lines += ["if u < acc:", f"    {push}", "    return"]
        lines.append(rest)                                   # the unpicked mass / rounding
        return lines

    def end(self, m) -> None:
        p = m.name
        self.fn(f"mx_end_{p}", "ctx, s, loc, cmd, out, i, code", self.leave_join(m) + [
            "if code > 0:",
            f"    out.mstat({self.stat[p] + 4} + code - 1, 1)",
            f"loc.{p}__st[i] = 0",
            f"loc.{p}__gen[i] += 1"] + self.end_more(m))

    def end_more(self, m) -> list[str]:
        return []

    def transition(self, m, t: int) -> None:
        st, kind, _key, target, chain = self.trans[m.name][t]
        if kind == "repeat":
            return self.repetition(m, t)
        if kind == "spawn":
            return self.spawn_op(m, t)
        p = m.name
        parts = chain.parts if chain is not None else ()
        if len(parts) > MAX_CHAIN_PARTS:          # the continuation tag holds q + 1 in 4 bits
            raise PackError(f"machine {p}: state {st.name!r}: a then-chain has more than "
                            f"{MAX_CHAIN_PARTS} parts ({len(parts)})")
        body = []
        if not parts:
            body += self.reserve(self.entry_need(m, target))
            body += [self.enter_call(m, target), "return COMMIT"]
            self.fn(f"mx_tr_{p}_{t}", "ctx, s, loc, cmd, out, i, part", body)
            return
        fail = (self.enter_call(m, st.on_reject) if st.on_reject is not None
                else f"mx_end_{p}(ctx, s, loc, cmd, out, i, 0)")
        fail_need = self.entry_need(m, st.on_reject) if st.on_reject else Need()
        for q, prt in enumerate(parts):
            call, need = self.make_part(m, st, prt.act, f"mx_part_{p}_{t}_{q}")
            fb_call = None
            if prt.fallback is not None:
                fb_call, fb_need = self.make_part(m, st, prt.fallback, f"mx_part_{p}_{t}_{q}f")
                need = need.union(fb_need)
            last = q == len(parts) - 1
            ok_need = self.entry_need(m, target) if last else Need(timers=1)
            need = need.add(ok_need.union(fail_need))
            body += [f"if part == {q}:", *("    " + x for x in self.reserve(need)),
                     f"    rc = {call}",
                     "    if rc != COMMIT:",
                     f"        out.mstat({self.stat[p] + 1}, 1)"]
            if fb_call is not None:
                body += [f"        rc = {fb_call}",
                         "        if rc != COMMIT:",             # a rejected fallback (D66)
                         f"            out.mstat({self.stat[p] + 1}, 1)"]
            body += ["    if rc != COMMIT:", f"        {fail}", "        return COMMIT"]
            body += self.after_part(m, st, t, q)                # Task 7 (until)
            if last:
                body.append(f"    {self.enter_call(m, target)}")
            else:
                body.append(f"    out.timer(ctx.t, MX_FIRE, prio=PRIO_CONTINUE, tag=mx_tag("
                            f"{m.index}, i, loc.{p}__gen[i], {L.OP_CHAIN}, {(t << 4) | (q + 1)}))")
            body.append("    return COMMIT")
        body.append("return reject(MX_STALE)")
        self.fn(f"mx_tr_{p}_{t}", "ctx, s, loc, cmd, out, i, part", body)

    def after_part(self, m, st, t, q) -> list[str]:
        return []

    def fire(self, m) -> None:
        p = m.name
        body = [f"if loc.{p}__st[i] == 0 or (loc.{p}__gen[i] & {L.GEN_MASK}) != g:",
                "    return reject(MX_STALE)",
                f"if op == {L.OP_CHAIN}:"]
        for t, tr in enumerate(self.trans[p]):
            if tr[1] not in ("branch", "timer"):
                continue
            body += [f"    if (x >> 4) == {t}:",
                     f"        return mx_tr_{p}_{t}(ctx, s, loc, cmd, out, i, x & 15)"]
        body += ["    return reject(MX_STALE)"]
        for t, (_st, kind, _key, _target, _chain) in enumerate(self.trans[p]):
            if kind in ("branch", "timer"):
                op = L.OP_BRANCH if kind == "branch" else L.OP_TIMER
                body += [f"if op == {op} and x == {t}:",
                         f"    return mx_tr_{p}_{t}(ctx, s, loc, cmd, out, i, 0)"]
        body += self.fire_more(m)                            # Tasks 7, 8
        body.append("return reject(MX_STALE)")
        self.fn(f"mx_fire_{p}", "ctx, s, loc, cmd, out, i, g, op, x", body)

    def fire_more(self, m) -> list[str]:
        p = m.name
        body = []
        for t, (_st, kind, *_rest) in enumerate(self.trans[p]):
            if kind == "repeat":
                body += [f"if op == {L.OP_REPEAT} and x == {t}:",
                         f"    return mx_rep_{p}_{t}(ctx, s, loc, cmd, out, i)"]
            elif kind == "spawn":
                body += [f"if op == {L.OP_SPAWN} and x == {t}:",
                         f"    return mx_sp_{p}_{t}(ctx, s, loc, cmd, out, i)"]
        names = {m.code(n): n for n in (*(s.name for s in m.states), *m.finals)}
        for code in sorted(self.now[p]):
            body += [f"if op == {L.OP_NOW} and x == {code}:",
                     *("    " + x for x in self.reserve(self.entry_need(m, names[code]))),
                     f"    {self.enter_call(m, names[code])}",
                     "    return COMMIT"]
        return body

    def init(self, m) -> None:
        p = m.name
        body = [f"loc.{p}__ep[i] += 1", f"loc.{p}__dep[i] = dep", f"loc.{p}__par[i] = par",
                f"loc.{p}__pm[i] = pm", f"loc.{p}__pep[i] = pep", f"loc.{p}__ord[i] = ord_",
                f"loc.{p}__kids[i] = 0", f"loc.{p}__jb[i] = 0", f"loc.{p}__jn[i] = 0",
                f"loc.{p}__jl[i] = 0", f"loc.{p}__actor[i] = actor",
                f"loc.{p}__pactor[i] = pactor"]
        body += [f"loc.{p}__{f}[i] = std.NULL" if t == "ref" else f"loc.{p}__{f}[i] = 0"
                 for f, t in m.fields.items()]
        self.fn(f"mx_init_{p}", "loc, i, dep, par, pm, pep, ord_, actor, pactor", body)
        self.fn(f"mx_alloc_{p}", "loc", [
            f"for j in range({m.max_instances}):",
            f"    if loc.{p}__st[j] == 0:",
            "        return j",
            "return -1"])

    def start(self) -> list[str] | None:
        started = [m for m in self.ms if m.start is not None]
        if not started:
            return None
        need = Need()
        body = []
        for m in started:
            need = need.add(self.entry_need(m, m.initial)).add(self.root_need(m))
        body += self.reserve(need)
        for m in started:
            body += [f"i = {0}",
                     *self.root_actor(m),
                     f"mx_init_{m.name}(loc, i, 0, -1, -1, 0, 0, actor, std.NULL)",
                     self.enter_call(m, m.initial)]
        body.append("return COMMIT")
        self.fn(f"mx_start_{self.part}", "ctx, s, loc, cmd, out", body)
        return body

    def root_need(self, m) -> Need:
        return Need()                                        # Task 10: member row creation

    def root_actor(self, m) -> list[str]:
        return ["actor = ctx.self_id"]                       # Task 10: out.add_member_<t>

    def root(self) -> None:
        p = self.part
        body = []
        if any(m.start is not None for m in self.ms):
            body += ["if cmd.kind == START:", f"    return mx_start_{p}(ctx, s, loc, cmd, out)"]
        body += ["if cmd.kind == MX_FIRE:",
                 "    m_ = (cmd.tag >> 41) & 15",
                 "    i_ = (cmd.tag >> 35) & 63",
                 f"    g_ = (cmd.tag >> 15) & {L.GEN_MASK}",
                 "    op_ = (cmd.tag >> 12) & 7",
                 "    x_ = cmd.tag & 4095"]
        for m in self.ms:
            body += [f"    if m_ == {m.index}:",
                     f"        return mx_fire_{m.name}(ctx, s, loc, cmd, out, i_, g_, op_, x_)"]
        body += ["    return reject(MX_STALE)"]
        body += self.root_more()                              # Task 8: responses
        body.append("return reject(MX_STALE)")
        self.fn(f"mx_{p}", "ctx, s, loc, cmd, out", body)

    def root_more(self) -> list[str]:
        return []

    # ---------------------------------------------------------------- everything
    def generate(self) -> MxProcess:
        self.fn("mx_tag", "m, i, g, op, x",
                [f"return (m << 41) | (i << 35) | ((g & {L.GEN_MASK}) << 15) | (op << 12) | x"])
        for m in self.ms:
            if len(m.states) + len(m.finals) >= L.TAG_X:      # OP_NOW carries a state code
                raise PackError(f"machine {m.name}: more than {L.TAG_X - 1} states and finals")
            self.init(m)
            self.end(m)
            for st in m.states:
                self.enter(m, st)
        for m in self.ms:                     # transitions after every entry assigned its ids
            for t in range(len(self.trans[m.name])):
                self.transition(m, t)
        for m in self.ms:                     # after every OP_NOW target is known (spawn, join)
            self.fire(m)
        self.start()
        self.root()
        body = "\n\n\n".join(self.funcs + self.copy_src)
        text = _HEADER.format(part=self.part) + "\n\n" + body + "\n"
        check_command_sites(self.part, text)
        return self.process(text)

    def config(self):
        fields, values = [], {}
        for m in self.ms:
            own = m.config if m.config is not None else _Pad()
            x = self.params[m.name] or {"pad": 0}
            X = dataclasses.make_dataclass(f"MxParams_{m.name}",
                                           [(k, type(v)) for k, v in x.items()], frozen=True)
            fields += [(f"c_{m.name}", type(own)), (f"x_{m.name}", X)]
            values[f"c_{m.name}"], values[f"x_{m.name}"] = own, X(**x)
        C = dataclasses.make_dataclass(f"MxConfig_{self.part}", fields, frozen=True)
        return C(**values)

    def process(self, text: str) -> MxProcess:
        if len(self.files) > 1:
            raise PackError(f"partition {self.part}: machine actions come from several files "
                            f"{sorted(self.files)}; keep one kernels file per partition")
        name = f"mx_{self.part}"
        commands = tuple(sorted({L.MX_FIRE, *self.responses.values(),
                                 *([START] if any(m.start for m in self.ms) else [])}))
        kernel = KernelSpec(name=name, func=None,
                            module_file=next(iter(self.files), f"<machines:{self.part}>"),
                            state=self.part, local=Local(**L.local_fields(self.ms)),
                            commands=commands, max=self.need.res(), substep=None,
                            params=VIEWS, source=None)
        reads, refs = {}, {}
        for m in self.ms:
            for d, src in ((reads, m.reads), (refs, m.refs)):
                for k, v in src.items():
                    if d.setdefault(k, v) != v:
                        raise PackError(f"partition {self.part}: machines disagree on {k!r}")
        start = next((m.start for m in self.ms if m.start is not None), None)
        depths = [m.max_spawn_depth for m in self.ms if m.max_spawn_depth is not None]
        return MxProcess(name, self.part, kernel, self.config(), start,
                         MappingProxyType(self.requests()), MappingProxyType(self.messages()),
                         MappingProxyType(dict(self.responses)),
                         MappingProxyType(reads), MappingProxyType(refs), commands,
                         min(depths) if depths else None, text)

    def requests(self) -> dict[str, str]:
        return {}                                            # Task 8

    def messages(self) -> dict[str, str]:
        return {}                                            # Task 8 (std.send parts)


def _sites_and_calls(nodes) -> tuple[set[int], set[str]]:
    sites, calls = set(), set()
    for n in (x for node in nodes for x in ast.walk(node)):
        if isinstance(n, ast.Call):
            if isinstance(n.func, ast.Name):
                calls.add(n.func.id)
            for kw in n.keywords:
                if kw.arg == "site" and isinstance(kw.value, ast.Constant):
                    sites.add(kw.value.value)
    return sites, calls


def check_command_sites(part: str, text: str) -> None:
    """The engine keeps at most `MAX_SITES` distinct draw sites per command (`rng.next_k`).
    A command's draws can span several site blocks (a spawn inlines the child's entry; a
    part calls an action copy), so count the sites each command reaches. Commands: a chain
    part (`mx_tr_*`, one per `if part == q:` block), a repetition, a spawn op, a state entry
    by `OP_NOW` and START."""
    funcs = {n.name: n for n in ast.parse(text).body if isinstance(n, ast.FunctionDef)}
    own = {name: _sites_and_calls([fn]) for name, fn in funcs.items()}

    def reach(sites: set[int], calls: set[str]) -> set[int]:
        out, todo, seen = set(sites), list(calls), set()
        while todo:
            f = todo.pop()
            if f in seen or f not in own:
                continue
            seen.add(f)
            out |= own[f][0]
            todo += own[f][1]
        return out

    roots: list[tuple[str, list]] = []
    for name, fn in funcs.items():
        if name.startswith("mx_tr_"):
            blocks = [st for st in fn.body if isinstance(st, ast.If)
                      and isinstance(st.test, ast.Compare)
                      and isinstance(st.test.left, ast.Name) and st.test.left.id == "part"]
            if blocks:
                roots += [(f"{name} part {b.test.comparators[0].value}", [b]) for b in blocks]
                continue
        if name.startswith(("mx_tr_", "mx_rep_", "mx_sp_", "mx_enter_", "mx_start_")):
            roots.append((name, [fn]))
    for name, nodes in roots:
        n = len(reach(*_sites_and_calls(nodes)))
        if n > MAX_SITES:
            raise PackError(f"partition {part}: command {name} draws from {n} sites; the engine "
                            f"allows {MAX_SITES} per command")


def compile_machines(plan, default_spawn_depth: int = 3) -> list[MxProcess]:
    """One `MxProcess` per owner partition that has machines, in partition order; the kernel
    source of each is its actions file followed by every machine text using that file."""
    out = []
    for part in plan.partitions:
        ms = [m for m in plan.machines if m.partition == part.name]
        if ms:
            out.append(_Gen(part.name, sorted(ms, key=lambda m: m.index), plan,
                            default_spawn_depth).generate())
    by_file: dict[str, list[MxProcess]] = {}
    for x in out:
        by_file.setdefault(x.kernel.module_file, []).append(x)
    final = []
    for x in out:
        group = by_file[x.kernel.module_file]
        head = ("" if x.kernel.module_file.startswith("<")
                else Path(x.kernel.module_file).read_text() + "\n\n")
        source = head + "\n\n".join(g.text for g in group)
        final.append(dataclasses.replace(
            x, kernel=dataclasses.replace(x.kernel, source=source)))
    return final
